/*
Data Types

A variable can store different kinds of information.

The three important types for this lesson are:
*/

// String - Text
let firstName = "Priya";
console.log("Name", firstName);
console.log(typeof firstName);

// Numbers
let age = 13;
console.log("Age", age);
console.log(typeof age);

// Boolean - true or false
let isStudent = true;
console.log("Is he/she is a student?", isStudent);
console.log(typeof isStudent);


